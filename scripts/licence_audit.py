"""Licence and access audit: for each source, look up open-access status and licences, and say what we may do.

Run from the project folder:  python3 -I scripts/licence_audit.py
Reads the seed papers and compilations from docs/inputs-needed.md; queries OpenAlex (open access),
Crossref (publisher licences, incl. text-and-data-mining licences) and DataCite (datasets).
Writes docs/licence-register.csv and docs/licence-register.md. Not legal advice: see the register page.
"""
import csv
import json
import re
import time
import urllib.parse
import urllib.request
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
UA = {"User-Agent": "diamond-inclusion-database licence audit (research project)"}  # no personal details sent


def get(url):
    try:
        with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=30) as r:
            return json.load(r)
    except Exception as e:  # a failed lookup is recorded, never guessed
        return {"_error": str(e)}


def sources():
    text = (ROOT / "docs" / "inputs-needed.md").read_text()
    for m in re.finditer(r"^\| (A\d+a?|B\d+) \| ([^|]+?) \| \[(10\.[^\]]+)\]", text, re.M):
        yield m[1], m[3], re.sub(r"\*", "", m[2]).split(". ")[0][:90]
    for m in re.finditer(r"\[(?:doi:)?(10\.(?:7939|5683)/[^\]\s]+)\]", text):
        yield "D0", m[1], "Dataset 0 compilation"


def classify(oa, licences):
    # OpenAlex uses short names ("cc-by-nc-nd"), Crossref full URLs ("creativecommons.org/licenses/by-nc-nd/")
    urls = " ".join(licences).lower().replace("creativecommons.org/licenses/", "cc-")
    if "publicdomain/zero" in urls or "cc0" in urls:
        return "open", "CC0: no restrictions. Reuse freely; cite as good practice."
    if "cc-by-nc" in urls:
        return "open_nc", ("CC BY-NC(-ND): free to read; show values with citation, non-commercial use only; "
                           "no modified copies of its text or figures.")
    if "cc-by" in urls:
        return "open", "CC BY: reuse with attribution, including short excerpts."
    if oa:
        return "free_to_read", "Free to read but no reuse licence: extract and show values with citation; no excerpts or figures."
    if "tdm" in urls:
        return "subscription_tdm", ("Subscription; the publisher offers a text-and-data-mining licence. Read via the library; "
                                    "show values with citation; keep quotes short (≤ 200 characters).")
    return "unknown", "Subscription, no mining licence listed. Ask the library before extracting at scale."


LABEL = {"open": "Open licence", "open_nc": "Open, non-commercial", "free_to_read": "Free to read, no licence",
         "subscription_tdm": "Subscription + mining licence", "unknown": "Check with library"}


def write_page(rows):
    count = lambda g: sum(r["group"] == g for r in rows)
    L = ["---", "tags: [legal, phase-4]", "---", "", "# Licence and access register", "",
         f"Generated by `scripts/licence_audit.py` on {date.today().isoformat()} from OpenAlex (open access), Crossref "
         "(publisher licences) and DataCite/Borealis (datasets). Re-run it when sources are added. "
         "**Not legal advice**: confirm publisher terms with the library before extracting at scale.", "",
         "Related: [roadmap](roadmap.md) (Phase 4) · [inputs needed](inputs-needed.md) · [log](log.md)", "",
         "## What the project shows, for every source", "",
         "- **Shown publicly:** extracted values (numbers, mineral names, classifications), the citation and DOI, and "
         "*where* each value was printed (page, table). Facts are not copyrighted; this is what compilations do.",
         "- **Never shown or shared:** PDFs, figures, page images, or passages of text. PDFs stay in `papers/` (never committed).",
         "- **Stored privately:** short evidence quotes, for traceability. Keep them ≤ 200 characters (the strictest "
         "common publisher limit) unless the source is CC BY or CC0.", "",
         "## Summary", "",
         "| Group | Sources |", "|---|---|",
         *[f"| {LABEL[g]} | {count(g)} |" for g in LABEL if count(g)], "",
         "## Sources", "",
         "| ID | Source | Publisher | Access | Licences found | What we may do |", "|---|---|---|---|---|---|"]
    for r in rows:
        L.append(f"| {r['id']} | [{r['title']}](https://doi.org/{r['doi']}) | {r['publisher']} | {r['oa_status'] or '?'} | "
                 f"{r['licences'] or '—'} | {r['what_we_may_do']}{' Lookup error: ' + r['lookup_error'] if r['lookup_error'] else ''} |")
    (ROOT / "docs" / "licence-register.md").write_text("\n".join(L) + "\n", encoding="utf-8")


def main():
    rows = []
    for key, doi, title in sources():
        if doi.startswith(("10.7939", "10.5683")):  # datasets are registered with DataCite, not Crossref
            dc = get("https://api.datacite.org/dois/" + urllib.parse.quote(doi.lower(), safe=""))
            rights = [r.get("rightsUri") or r.get("rights", "") for r in (dc.get("data", {}).get("attributes", {})
                                                                         .get("rightsList") or [])]
            oa, oa_status, publisher, oa_url = True, "dataset", (dc.get("data", {}).get("attributes", {}).get("publisher")
                                                                 or ""), "https://doi.org/" + doi
            licences, err = rights, dc.get("_error", "")
            if not licences:  # DataCite record lacks it: ask the repository itself (Dataverse API)
                bor = get("https://borealisdata.ca/api/datasets/:persistentId/?persistentId=doi:" + doi)
                lic = ((bor.get("data") or {}).get("latestVersion") or {}).get("license") or {}
                if lic:
                    licences = [f'{lic.get("name")} ({lic.get("uri", "Borealis")})']
        else:
            ox = get("https://api.openalex.org/works/doi:" + urllib.parse.quote(doi, safe="/"))
            cr = get("https://api.crossref.org/works/" + urllib.parse.quote(doi, safe="/"))
            msg = cr.get("message", {})
            licences = [f'{l.get("URL")} ({l.get("content-version")})' for l in msg.get("license", [])]
            best = (ox.get("best_oa_location") or {})
            if best.get("license"):
                licences.append(f'{best["license"]} (OpenAlex)')
            oa = (ox.get("open_access") or {}).get("is_oa")
            oa_status = (ox.get("open_access") or {}).get("oa_status")
            oa_url = (ox.get("open_access") or {}).get("oa_url") or ""
            publisher = msg.get("publisher", "")
            err = "; ".join(x for x in [ox.get("_error", ""), cr.get("_error", "")] if x)
        group, what = classify(oa, licences)
        rows.append({"id": key, "doi": doi, "title": title, "publisher": publisher, "open_access": oa,
                     "oa_status": oa_status, "oa_url": oa_url, "licences": " | ".join(licences),
                     "group": group, "what_we_may_do": what, "lookup_error": err})
        time.sleep(0.5)  # be polite to the free APIs

    write_page(rows)
    with open(ROOT / "docs" / "licence-register.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    print(json.dumps([{k: r[k] for k in ("id", "doi", "publisher", "oa_status", "licences", "group", "lookup_error")}
                      for r in rows], ensure_ascii=False, indent=1))


if __name__ == "__main__":
    main()
